"""Offline fake curator for the S2/S3 layouts in evaluation spec §7 E3.

This module is deliberately part of the evaluation package rather than
``harnext_builder``.  It is a deterministic, semantic stand-in for the LLM
builder used by smoke tests; reportable online runs still use the configured
builder harness.
"""

from __future__ import annotations

import json
import shutil
from collections import defaultdict
from pathlib import Path
from typing import Any

from harnext_eval.stores.base import StoreHandle
from harnext_eval.stores.fake_usage import estimate_fake_fold_usage
from harnext_eval.stores.layouts import ordered_events, safe_component
from harnext_eval.stores.templated import entity_relpath, structured_updates
from harnext_eval.types import EvalEvent

FAKE_CURATOR_MODEL = "offline-fake-curator-v1"
_STATE_PATH = "_meta/fake_curator_state.json"
_LABEL_PATH = "_meta/fake-curator.md"
_CONTROL_FIELDS = {"changelog", "field", "from", "state", "to"}


def _text_value(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return value.replace("\n", " ").strip()
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def _field_name(value: object) -> str:
    return str(value).replace("\n", " ").strip() or "field"


def _curated_updates(event: EvalEvent) -> dict[str, str]:
    """Return current facts while preserving non-S1 source-specific fields."""

    updates = dict(structured_updates(event))
    data = event.data or {}
    state = data.get("state")
    if isinstance(state, dict):
        for raw_field, value in state.items():
            updates.setdefault(_field_name(raw_field), _text_value(value))
    for raw_field, value in data.items():
        field = _field_name(raw_field)
        if field.casefold() in _CONTROL_FIELDS:
            continue
        updates.setdefault(field, _text_value(value))
    return dict(sorted(updates.items(), key=lambda item: item[0].casefold()))


def _load_state(store: StoreHandle) -> dict[str, dict[str, Any]]:
    path = store.worktree / _STATE_PATH
    if not path.exists():
        return {}
    loaded = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(loaded, dict):
        raise ValueError(f"invalid fake curator state at {path}")
    return loaded


def _write_state(store: StoreHandle, state: dict[str, dict[str, Any]]) -> None:
    store.write(_STATE_PATH, json.dumps(state, indent=2, sort_keys=True) + "\n")


def _append(path: Path, heading: str, body: str) -> None:
    existing = path.read_text(encoding="utf-8").rstrip() if path.exists() else heading
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"{existing}\n{body.rstrip()}\n", encoding="utf-8")


def _append_superseded(
    store: StoreHandle,
    subject: str,
    field: str,
    previous: dict[str, str],
    replacement: dict[str, str],
) -> None:
    line = (
        f"- {subject}: {field}={previous['value']} "
        f"[{previous['source']}#{previous['event_id']}] was superseded by "
        f"{field}={replacement['value']} on {replacement['time']} "
        f"[{replacement['source']}#{replacement['event_id']}]"
    )
    _append(store.worktree / "_meta" / "superseded.md", "# Superseded Facts", line)


def _append_timeline(store: StoreHandle, event: EvalEvent, lane: str) -> str:
    relpath = f"{entity_relpath(event.subject)}/timeline.md"
    record = json.dumps(event.model_dump(mode="json"), ensure_ascii=False, sort_keys=True)
    body = (
        f"\n## {event.time.isoformat()} — {event.id}\n\n"
        f"- Provenance: [{event.source}#{event.id}]\n"
        f"- Lane: {lane}\n"
        f"- Event type: {event.type}\n\n"
        f"```json\n{record}\n```"
    )
    _append(store.worktree / relpath, f"# Curated timeline for {event.subject}", body)
    return relpath


def _write_entity_projection(
    store: StoreHandle,
    subject: str,
    entity_state: dict[str, Any],
) -> list[str]:
    relroot = entity_relpath(subject)
    facts = entity_state.get("facts", {})
    last_event = entity_state["last_event"]
    overview_lines = [
        f"# {subject}",
        "",
        "> Generated by the deterministic offline fake curator; this is a smoke-test stand-in for the LLM builder.",
        "",
        f"_Last updated: {last_event['time']} [{last_event['source']}#{last_event['event_id']}]_",
        "",
        "## Curated current state",
        "",
    ]
    fact_lines = [
        f"# Curated facts for {subject}",
        "",
        "_One current atomic value per field; retired values live in `_meta/superseded.md`._",
        "",
    ]
    for field in sorted(facts, key=str.casefold):
        fact = facts[field]
        overview_lines.append(f"- {field}: {fact['value']}")
        fact_lines.append(
            f"- {fact['time'][:10]} [{fact['source']}#{fact['event_id']}] "
            f"{field}={fact['value']}"
        )
    overview_lines.extend(
        [
            "",
            "## Evidence",
            "",
            f"- Latest event: {last_event['event_id']}",
            "- Timeline: [timeline.md](timeline.md)",
            "- Atomic facts: [facts.md](facts.md)",
        ]
    )
    overview_path = f"{relroot}/OVERVIEW.md"
    facts_path = f"{relroot}/facts.md"
    store.write(overview_path, "\n".join(overview_lines).rstrip() + "\n")
    store.write(facts_path, "\n".join(fact_lines).rstrip() + "\n")
    return [overview_path, facts_path]


def _rebuild_global_organisation(
    store: StoreHandle,
    state: dict[str, dict[str, Any]],
) -> list[str]:
    rows: list[tuple[str, str, str, str]] = []
    by_type: dict[str, list[tuple[str, str, str]]] = defaultdict(list)
    for subject, entity_state in state.items():
        relpath = f"{entity_relpath(subject)}/OVERVIEW.md"
        entity_type = subject.split(":", 1)[0] if ":" in subject else "entity"
        updated = str(entity_state["last_event"]["time"])
        rows.append((subject, entity_type, updated, relpath))
        by_type[entity_type].append((subject, updated, relpath))
    rows.sort(key=lambda row: (row[0].casefold(), row[3]))
    index_lines = [
        "# Org Context Index",
        "",
        "> Deterministic offline fake-curator output (stand-in for the LLM builder).",
        "",
        "| Entity | Type | Last updated | Overview |",
        "|--------|------|--------------|----------|",
    ]
    index_lines.extend(
        f"| {subject} | {kind} | {updated} | [{path}]({path}) |"
        for subject, kind, updated, path in rows
    )
    store.write("INDEX.md", "\n".join(index_lines) + "\n")
    touched = ["INDEX.md"]

    topics = store.worktree / "topics"
    if topics.exists():
        for path in topics.iterdir():
            if path.is_file():
                path.unlink()
            elif path.is_dir():
                shutil.rmtree(path)
    for entity_type, entries in sorted(by_type.items()):
        topic_path = f"topics/{safe_component(entity_type)}.md"
        topic_lines = [
            f"# {entity_type} entities",
            "",
            "> Deterministic navigation generated by the offline fake curator.",
            "",
        ]
        topic_lines.extend(
            f"- [{subject}](../{relpath}) — updated {updated}"
            for subject, updated, relpath in sorted(entries)
        )
        store.write(topic_path, "\n".join(topic_lines).rstrip() + "\n")
        touched.append(topic_path)
    return touched


def _remove_global_organisation(store: StoreHandle) -> None:
    index = store.worktree / "INDEX.md"
    if index.exists():
        index.unlink()
    topics = store.worktree / "topics"
    if topics.exists():
        shutil.rmtree(topics)


def _record_usage(
    store: StoreHandle,
    events: list[EvalEvent],
    lane: str,
    touched: set[str],
    before_sizes: dict[str, int],
) -> None:
    files_read_bytes = sum(before_sizes.get(relpath, 0) for relpath in touched)
    bytes_written = sum(
        path.stat().st_size
        for relpath in touched
        if (path := store.worktree / relpath).is_file()
    )
    usage = estimate_fake_fold_usage(
        events,
        files_read_bytes=files_read_bytes,
        bytes_written=bytes_written,
    )
    row = {
        "cost_usd": usage.cost_usd,
        "event_count": len(events),
        "event_ids": [event.id for event in ordered_events(events)],
        "files_touched": sorted(touched),
        "harness": "fake",
        "input_tokens": usage.input_tokens,
        "lane": lane,
        "layout": store.layout,
        "model": FAKE_CURATOR_MODEL,
        "output_tokens": usage.output_tokens,
        "status": "success",
        "stop_reason": "offline_fake_curator_complete",
        "tokens_in": usage.input_tokens,
        "tokens_out": usage.output_tokens,
        "total_cost_usd": usage.cost_usd,
        "usage": {
            "bytes_written": usage.bytes_written,
            "files_read_bytes": usage.files_read_bytes,
            "instruction_bytes": usage.instruction_bytes,
        },
    }
    usage_path = store.root / "usage.jsonl"
    usage_path.parent.mkdir(parents=True, exist_ok=True)
    with usage_path.open("a", encoding="utf-8") as destination:
        destination.write(json.dumps(row, sort_keys=True) + "\n")


def curate_events(
    store: StoreHandle,
    events: list[EvalEvent],
    lane: str,
    *,
    global_organisation: bool,
) -> None:
    """Curate every event into current facts, overview, and an audit timeline."""

    before_sizes = {
        path.relative_to(store.worktree).as_posix(): path.stat().st_size
        for path in store.worktree.rglob("*")
        if path.is_file() and ".git" not in path.parts
    }
    state = _load_state(store)
    touched: set[str] = {_STATE_PATH, _LABEL_PATH, "_meta/superseded.md"}
    affected: set[str] = set()
    for event in ordered_events(events):
        subject_state = state.setdefault(event.subject, {"facts": {}})
        facts = subject_state.setdefault("facts", {})
        for field, value in _curated_updates(event).items():
            replacement = {
                "event_id": event.id,
                "source": event.source,
                "time": event.time.isoformat(),
                "value": value,
            }
            previous = facts.get(field)
            if isinstance(previous, dict) and previous.get("value") != value:
                _append_superseded(store, event.subject, field, previous, replacement)
            facts[field] = replacement
        subject_state["last_event"] = {
            "event_id": event.id,
            "source": event.source,
            "time": event.time.isoformat(),
            "type": event.type,
        }
        touched.add(_append_timeline(store, event, lane))
        affected.add(event.subject)

    for subject in sorted(affected, key=str.casefold):
        touched.update(_write_entity_projection(store, subject, state[subject]))
    _write_state(store, state)
    store.write(
        _LABEL_PATH,
        "# Offline fake curator\n\n"
        "This store was curated deterministically for offline smoke tests. It is a "
        "stand-in for, not an execution of, the LLM builder.\n",
    )
    if global_organisation:
        touched.update(_rebuild_global_organisation(store, state))
    else:
        _remove_global_organisation(store)
    _record_usage(store, events, lane, touched, before_sizes)


__all__ = ["FAKE_CURATOR_MODEL", "curate_events"]
