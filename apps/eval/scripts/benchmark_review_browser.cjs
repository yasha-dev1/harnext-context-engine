// Browser verification of the local review artifact; never launches an agent.
const { chromium } = require(process.env.HARNEXT_PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');

(async()=>{
  const root=path.resolve('apps/eval/benchmarks/kafka-1000-v1');
  const bundle=JSON.parse(fs.readFileSync(path.join(root,'data/review-bundle.json'),'utf8'));
  const browser=await chromium.launch({headless:true,...(process.env.HARNEXT_CHROMIUM_PATH?{executablePath:process.env.HARNEXT_CHROMIUM_PATH}:{}),args:['--no-sandbox']});
  const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
  const page=await context.newPage();const errors=[],remote=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(/^https?:/.test(r.url()))remote.push(r.url())});
  await page.goto(pathToFileURL(path.join(root,'review.html')).href);
  await page.waitForFunction(()=>window.benchmarkReview?.taskCount===1000);
  assert.equal(await page.locator('#countTotal').innerText(),'1,000');
  assert.equal(await page.locator('#countHistory').innerText(),'800');
  assert.equal(await page.locator('#countCoding').innerText(),'200');
  await page.locator('#kind').selectOption('coding');
  assert.equal(await page.locator('#matchCount').innerText(),'200 matches');
  await page.locator('.task-row').first().click();
  await page.getByRole('tab',{name:'Tests & real PR'}).click();
  assert(await page.getByText('Evaluator-only real implementation patch',{exact:true}).isVisible());
  await page.screenshot({path:path.join(root,'data/review-coding.png'),fullPage:true});
  await page.getByRole('tab',{name:'Agent input'}).click();
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download agent prompt'}).click();
  const promptDownload=await download;
  const text=fs.readFileSync(await promptDownload.path(),'utf8');
  const selected=await page.evaluate(()=>window.benchmarkReview.getSelected());
  assert.equal(text,bundle.tasks.find(t=>t.id===selected).agent_prompt);
  await page.getByRole('button',{name:'Needs changes',exact:true}).click();
  await page.getByRole('textbox',{name:'Review notes'}).fill('Browser verification note; isolated test profile.');
  assert.equal(await page.locator('#countReviewed').innerText(),'1');
  const reviewsDownload=page.waitForEvent('download');
  await page.locator('#exportReviews').click();
  const exported=JSON.parse(fs.readFileSync(await (await reviewsDownload).path(),'utf8'));
  assert.equal(exported.tasks_sha256,bundle.manifest.tasks_sha256);
  assert.equal(exported.reviews[selected].status,'change');
  await page.reload();await page.waitForFunction(()=>window.benchmarkReview?.taskCount===1000);
  assert.equal(await page.locator('#countReviewed').innerText(),'1');
  await page.getByRole('button',{name:'Pending',exact:true}).click();
  assert.equal(await page.locator('#countReviewed').innerText(),'0');
  await page.locator('#importFile').setInputFiles({name:'reviews.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(exported))});
  await page.waitForFunction(()=>document.getElementById('countReviewed').textContent==='1');
  await page.getByRole('button',{name:'Pending',exact:true}).click();
  await page.getByRole('textbox',{name:'Review notes'}).fill('');
  await page.locator('#kind').selectOption('historical');
  await page.locator('#family').selectOption('closed_at_snapshot');
  assert.equal(await page.locator('#matchCount').innerText(),'100 matches');
  await page.locator('.task-row').first().click();
  await page.getByRole('tab',{name:'Expected answer'}).click();
  assert(await page.getByText('Deterministic expected value',{exact:true}).isVisible());
  await page.getByRole('tab',{name:'Evidence & references'}).click();
  await page.locator('details.evidence').first().locator('summary').click();
  await page.screenshot({path:path.join(root,'data/review-history.png'),fullPage:true});
  await page.locator('#family').selectOption('');await page.locator('#kind').selectOption('');
  await page.locator('#search').fill('NO_SUCH_ISSUE_XXXXXXXX');
  assert.equal(await page.locator('#matchCount').innerText(),'0 matches');
  await page.locator('#search').fill('');
  await page.locator('#overviewToggle').click();
  await page.screenshot({path:path.join(root,'data/review-overview.png'),fullPage:true});
  await page.locator('#overviewToggle').click();
  await page.getByRole('tab',{name:'Agent input'}).click();
  // Exercise rendering for every embedded instance, including the final record.
  const checked=await page.evaluate(ids=>{let count=0;for(const id of ids){window.benchmarkReview.selectId(id);if(!document.querySelector('.text-box')?.textContent)throw Error('Missing prompt: '+id);count++}return count},bundle.tasks.map(t=>t.id));
  assert.equal(checked,1000);
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.screenshot({path:path.join(root,'data/review-mobile.png'),fullPage:true});
  assert.deepEqual(errors,[]);assert.deepEqual(remote,[]);
  fs.writeFileSync(path.join(root,'data/browser-validation.json'),JSON.stringify({passed:true,rendered_instances:checked,console_errors:errors,external_requests:remote,checks:['counts','filters','search-empty-state','detail-tabs','prompt-download-exact','review-persistence','review-export','review-import','all-1000-prompts','mobile-no-overflow'],browser:await browser.version(),tasks_sha256:bundle.manifest.tasks_sha256},null,2));
  console.log(JSON.stringify({passed:true,rendered_instances:checked,console_errors:errors.length,external_requests:remote.length}));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
